    def get_format_position_hint(self, index: int, total_blocks: int) -> str:
        if total_blocks <= 1:
            return ""
        if index == 0:
            return (
                "\n\nमहत्वपूर्ण: यह बहु-भाग दस्तावेज़ का ब्लॉक 1/{total} है। "
                "इस अनुभाग को दस्तावेज़ के आरंभ के रूप में प्रारूपित करें। "
                "यदि सामग्री उचित हो तो परिचय शामिल कर सकते हैं। "
                "निष्कर्ष या समापन टिप्पणी न जोड़ें।"
            ).format(total=total_blocks)
        if index == total_blocks - 1:
            return (
                "\n\nमहत्वपूर्ण: यह बहु-भाग दस्तावेज़ का ब्लॉक {idx}/{total} (अंतिम ब्लॉक) है। "
                "इस अनुभाग को दस्तावेज़ के समापन के रूप में प्रारूपित करें। "
                "यदि सामग्री उचित हो तो निष्कर्ष शामिल कर सकते हैं। "
                "नया परिचय न जोड़ें और क्रमांकन फिर से शुरू न करें।"
            ).format(idx=index + 1, total=total_blocks)
        return (
            "\n\nमहत्वपूर्ण: यह बहु-भाग दस्तावेज़ का ब्लॉक {idx}/{total} (मध्य ब्लॉक) है। "
            "इसे दस्तावेज़ की निरंतरता के रूप में प्रारूपित करें। "
            "परिचय न जोड़ें, निष्कर्ष न जोड़ें, अनुभाग क्रमांकन फिर से शुरू न करें।"
        ).format(idx=index + 1, total=total_blocks)

