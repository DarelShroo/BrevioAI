    def get_format_position_hint(self, index: int, total_blocks: int) -> str:
        if total_blocks <= 1:
            return ""
        if index == 0:
            return (
                "\n\nمهم: هذه الكتلة 1 من {total} في مستند متعدد الأجزاء. "
                "نسّق هذا القسم كافتتاح للمستند. "
                "يمكنك تضمين مقدمة إذا برّر المحتوى ذلك. "
                "لا تُضف خاتمة أو ملاحظات إغلاق."
            ).format(total=total_blocks)
        if index == total_blocks - 1:
            return (
                "\n\nمهم: هذه الكتلة {idx} من {total} (الكتلة الأخيرة) في مستند متعدد الأجزاء. "
                "نسّق هذا القسم كخاتمة للمستند. "
                "يمكنك تضمين خاتمة إذا برّر المحتوى ذلك. "
                "لا تُضف مقدمة جديدة ولا تُعد بدء الترقيم."
            ).format(idx=index + 1, total=total_blocks)
        return (
            "\n\nمهم: هذه الكتلة {idx} من {total} (كتلة وسطى) في مستند متعدد الأجزاء. "
            "نسّقها كاستمرار للمستند. "
            "لا تُضف مقدمة ولا خاتمة ولا تُعد بدء ترقيم الأقسام."
        ).format(idx=index + 1, total=total_blocks)

