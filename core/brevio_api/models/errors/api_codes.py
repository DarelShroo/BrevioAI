from enum import Enum

from fastapi import HTTPException


class ApiErrorCode(str, Enum):
    FOLDER_NAME_INVALID = "FOLDER_NAME_INVALID"
    FOLDER_NAME_TOO_LONG = "FOLDER_NAME_TOO_LONG"
    FOLDER_NAME_DUPLICATE = "FOLDER_NAME_DUPLICATE"
    FOLDER_NOT_FOUND = "FOLDER_NOT_FOUND"
    FOLDER_FORBIDDEN = "FOLDER_FORBIDDEN"
    ENTRY_NAME_INVALID = "ENTRY_NAME_INVALID"
    ENTRY_NAME_TOO_LONG = "ENTRY_NAME_TOO_LONG"
    ENTRY_NOT_FOUND = "ENTRY_NOT_FOUND"
    ENTRY_FORBIDDEN = "ENTRY_FORBIDDEN"
    ENTRY_IDS_REQUIRED = "ENTRY_IDS_REQUIRED"
    FILE_FORMAT_NOT_ALLOWED = "FILE_FORMAT_NOT_ALLOWED"
    MEDIA_FORMAT_NOT_ALLOWED = "MEDIA_FORMAT_NOT_ALLOWED"
    MEDIA_FILE_CORRUPT = "MEDIA_FILE_CORRUPT"
    MEDIA_NO_AUDIO_TRACK = "MEDIA_NO_AUDIO_TRACK"
    MEDIA_FFMPEG_ERROR = "MEDIA_FFMPEG_ERROR"
    MEDIA_FFMPEG_TIMEOUT = "MEDIA_FFMPEG_TIMEOUT"
    TRANSCRIPTION_PROVIDER_NOT_ALLOWED = "TRANSCRIPTION_PROVIDER_NOT_ALLOWED"
    TRANSCRIPTION_PROVIDER_UNKNOWN = "TRANSCRIPTION_PROVIDER_UNKNOWN"
    TRANSCRIPTION_API_KEY_REQUIRED = "TRANSCRIPTION_API_KEY_REQUIRED"
    TRANSCRIPTION_API_KEY_INVALID = "TRANSCRIPTION_API_KEY_INVALID"
    TRANSCRIPTION_OPENAI_ERROR = "TRANSCRIPTION_OPENAI_ERROR"
    TRANSCRIPTION_OPENAI_TIMEOUT = "TRANSCRIPTION_OPENAI_TIMEOUT"
    TRANSCRIPTION_LOCAL_WHISPER_ERROR = "TRANSCRIPTION_LOCAL_WHISPER_ERROR"
    TRANSCRIPTION_TIMEOUT = "TRANSCRIPTION_TIMEOUT"
    TRANSCRIPTION_FAILED = "TRANSCRIPTION_FAILED"
    TRANSCRIPTION_QUOTA_EXCEEDED = "TRANSCRIPTION_QUOTA_EXCEEDED"
    SUMMARY_AFTER_TRANSCRIPTION_FAILED = "SUMMARY_AFTER_TRANSCRIPTION_FAILED"
    MODEL_NOT_ALLOWED = "MODEL_NOT_ALLOWED"
    GENERATION_PARAM_INVALID = "GENERATION_PARAM_INVALID"


class CodedHTTPException(HTTPException):
    def __init__(
        self, status_code: int, code: ApiErrorCode | str, detail: str | None = None
    ):
        code_value = code.value if isinstance(code, ApiErrorCode) else code
        super().__init__(status_code=status_code, detail=detail or code_value)
        self.code = code_value
